#!/usr/bin/env node
/**
 * Promtly bridge — the local half of promtly.dev.
 *
 * A browser tab cannot focus another window, press Ctrl+V, or answer a
 * global hotkey. Those are hard sandbox boundaries, not missing
 * permissions. This process does the parts the page is not allowed to,
 * and it is what turns a web page full of buttons into a launcher:
 *
 *   Ctrl+Alt+Space  summon — remember the window you are in, then bring
 *                   the board up over it. Firing a pad pastes back into
 *                   the window you were in when you summoned it.
 *   Ctrl+Alt+C      capture — copy whatever is selected anywhere on the
 *                   machine and turn it into a new pad.
 *
 * It also SERVES the board at http://127.0.0.1:37222, mirrored from
 * promtly.dev. That is not a convenience: a page on https://promtly.dev
 * cannot reliably reach 127.0.0.1 (Chrome gates public-to-loopback, and
 * a gated request hangs silently — measured, curl answered the identical
 * request in 2 ms). Served from here, the page is SAME-ORIGIN with this
 * process and there is nothing to permit.
 *
 * Targeting is verified, never assumed. If the window switch does not
 * take, it refuses to send the keystroke rather than firing a paste into
 * whatever is still in front.
 *
 * No dependencies. No installer.
 *
 *     node promtly-bridge.mjs
 *
 * Windows only for now (it drives user32 through long-lived PowerShell
 * hosts). Elsewhere it starts, mirrors the board, and says so.
 */

