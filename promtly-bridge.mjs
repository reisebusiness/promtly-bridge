function openLauncherWindow() {
  const exe = findBrowser();
  if (!exe) {
    log("no Chrome or Edge found — open http://127.0.0.1:" + PORT + "/launch yourself.");
    return false;
  }
  // An --app window is a real OS window with its own title and no browser
  // chrome, which is what makes "summon" feel like a launcher rather than a
  // tab hunt.
  const child = spawn(
    exe,
    [`--app=http://127.0.0.1:${PORT}/launch`, "--window-size=560,680"],
    { detached: true, stdio: "ignore" },
  );
  child.unref();
  // !! Then MOVE it. Chrome's --window-position is measured from the primary
  // display's origin and knows nothing about the taskbar, so the bridge places
  // the window itself once it exists - right edge, inside the work area. Every
  // assistant keeps its conversation list down the left, and a launcher that
  // opens centred covers the thing you were reading.
  //
  // Polled rather than awaited: Chrome forks, and the window does not exist
  // when spawn() returns. Six tries at 400ms covers a cold start without
  // leaving a timer running if the window never appears.
  if (driver) {
    let tries = 0;
    const settle = setInterval(() => {
      tries += 1;
      driver
        .place("full")
        .then((reply) => {
          if (reply.status === "ok" || tries >= 6) clearInterval(settle);
        })
        .catch(() => {
          if (tries >= 6) clearInterval(settle);
        });
    }, 400);
  }
  return true;
}

class HotkeyHost {
  constructor(onHotkey) {
    this.onHotkey = onHotkey;
    this.proc = null;
    this.buffer = "";
    this.registered = null;
  }

  start() {
    this.proc = spawnPowerShell(PS_HOTKEYS, "promtly-keys");
    this.proc.stdout.setEncoding("utf8");
    this.proc.stdout.on("data", (chunk) => {
      this.buffer += chunk;
      let index = this.buffer.indexOf("\n");
      while (index !== -1) {
        const line = this.buffer.slice(0, index).trim();
        this.buffer = this.buffer.slice(index + 1);
        if (line.startsWith("K ready")) {
          const [summon, capture] = line.slice("K ready".length).trim().split("|");
          this.registered = {
            summon: summon && summon !== "-" ? summon : null,
            capture: capture && capture !== "-" ? capture : null,
          };
          log("");
          log(
            this.registered.summon
              ? `  ${this.registered.summon.padEnd(16)} summon the launcher over whatever you are in`
              : "  (no chord free)    summon hotkey unavailable — every candidate is taken",
          );
          log(
            this.registered.capture
              ? `  ${this.registered.capture.padEnd(16)} turn the current selection into a new pad`
              : "  (no chord free)    capture hotkey unavailable — every candidate is taken",
          );
          log("");
        } else if (line.startsWith("K hot")) {
          const id = Number(line.split(" ")[2]);
          if (id) void this.onHotkey(id);
        }
        index = this.buffer.indexOf("\n");
      }
    });
    this.proc.on("exit", (code) => {
      this.proc = null;
      log(`hotkey host exited (${code}); global shortcuts are off.`);
    });
  }
}

