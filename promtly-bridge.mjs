function ensureLocalDir() {
  try {
    if (!existsSync(LOCAL_DIR)) mkdirSync(LOCAL_DIR, { recursive: true });
    if (!existsSync(THEME_FILE)) writeFileSync(THEME_FILE, THEME_SEED, "utf8");
    // ⚠ Rewrite the guide when it drifts, unlike theme.css which is the
    // user's own file. This doc is what gets handed to a model; a stale token
    // table is worse than no table, because the model styles confidently
    // against defaults that were retired two versions ago.
    let guideOnDisk = "";
    try {
      guideOnDisk = existsSync(GUIDE_FILE) ? readFileSync(GUIDE_FILE, "utf8") : "";
    } catch {
      guideOnDisk = "";
    }
    if (guideOnDisk !== CUSTOMIZE_GUIDE) writeFileSync(GUIDE_FILE, CUSTOMIZE_GUIDE, "utf8");
    return true;
  } catch (err) {
    log(`could not prepare ${LOCAL_DIR}: ${String(err && err.message ? err.message : err)}`);
    return false;
  }
}

function localStamp() {
  const stamp = (file) => {
    try {
      return existsSync(file) ? String(statSync(file).mtimeMs) : "0";
    } catch {
      return "0";
    }
  };
  return `${stamp(THEME_FILE)}-${stamp(CUSTOM_JS)}`;
}

function readLocal(file) {
  try {
    return existsSync(file) ? readFileSync(file, "utf8") : "";
  } catch {
    return "";
  }
}

/**
 * Inject the local layer into the mirrored page.
 *
 * The stylesheet goes LAST in <head> so it outranks the bundle's tokens
 * without needing !important. The watcher swaps only the stylesheet href on
 * change, so a restyle does not reload the page and lose what you were
 * typing.
 */
function injectLocalLayer(html) {
  const version = localStamp();
  const hasCustomJs = existsSync(CUSTOM_JS);
  const tags =
    `
<link id="promtly-local-theme" rel="stylesheet" href="/local/theme.css?v=${version}">` +
    (hasCustomJs ? `
<script src="/local/custom.js?v=${version}" defer></script>` : "") +
    `
<script>(function(){var v=${JSON.stringify(version)};setInterval(function(){` +
    `fetch("/local/version",{cache:"no-store"}).then(function(r){return r.text()}).then(function(n){` +
    `if(n===v)return;v=n;var l=document.getElementById("promtly-local-theme");` +
    `if(l)l.setAttribute("href","/local/theme.css?v="+encodeURIComponent(n));` +
    `else location.reload();}).catch(function(){});},1500);})();</script>
`;

  return html.includes("</head>") ? html.replace("</head>", `${tags}</head>`) : html + tags;
}

