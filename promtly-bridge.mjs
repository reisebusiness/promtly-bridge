// ---------------------------------------------------------------------------
// HTTP. Loopback only, and an Origin allowlist — a browser cannot forge
// Origin from script, so a hostile page cannot reach this even though the
// port is open.
// ---------------------------------------------------------------------------

function corsHeaders(origin) {
  return {
    "Access-Control-Allow-Origin": origin,
    "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
    "Access-Control-Allow-Headers": "content-type",
    "Access-Control-Max-Age": "600",
    // Load-bearing for the hosted board: Chrome gates public-to-loopback
    // behind Private Network Access and blocks the real request unless the
    // preflight grants it. Necessary but NOT sufficient — see the mirror.
    "Access-Control-Allow-Private-Network": "true",
    Vary: "Origin",
  };
}

function send(res, status, body, origin) {
  res.writeHead(status, {
    "Content-Type": "application/json; charset=utf-8",
    "Cache-Control": "no-store",
    ...(origin ? corsHeaders(origin) : {}),
  });
  res.end(JSON.stringify(body));
}

function readJson(req) {
  return new Promise((resolve, reject) => {
    let raw = "";
    let size = 0;
    req.on("data", (chunk) => {
      size += chunk.length;
      // A prompt is text. Anything past this is not a prompt.
      if (size > 1000000) {
        reject(new Error("payload too large"));
        req.destroy();
        return;
      }
      raw += chunk;
    });
    req.on("end", () => {
      try {
        resolve(raw ? JSON.parse(raw) : {});
      } catch (err) {
        reject(err);
      }
    });
    req.on("error", reject);
  });
}

function log(line) {
  const stamp = new Date().toTimeString().slice(0, 8);
  process.stdout.write(`[${stamp}] ${line}\n`);
}

// ---------------------------------------------------------------------------
// The mirror cache.
//
// ⭐ Without this the bridge refetched promtly.dev for EVERY asset on EVERY
// launcher open, with Cache-Control: no-store — so summoning the launcher
// re-downloaded the whole app, and with no connection it did not open at all.
// A local launcher that needs the internet to show you your own prompts is
// the wrong shape.
//
// Stale-while-revalidate: a cached response is served immediately and, if it
// is past FRESH_MS, revalidated in the background with If-None-Match so a
// deploy still lands within one open. If upstream fails and anything is
// cached, the cache wins — that is the offline case, and it is deliberate.
//
// HTML is cached RAW and the local theme/script layer is injected at serve
// time, so a cached page can never bake in a stale layer.
// ---------------------------------------------------------------------------

const CACHE_DIR = join(LOCAL_DIR, "cache");
/** Past this, a hit is still served but revalidated behind the response. */
const FRESH_MS = 60_000;
/** Bodies larger than this are streamed through and not stored. */
const CACHE_MAX_BYTES = 8 * 1024 * 1024;

/** Revalidations in flight, so a burst of hits cannot stack up fetches. */
const revalidating = new Set();

/**
 * Drop cache entries nothing has asked for in a fortnight.
 *
 * The mirrored site is a few dozen stable files, so this is not about size -
 * it is about renames. Next.js fingerprints its chunks, so every deploy
 * retires a filename permanently, and without a sweep those dead entries sit
 * on disk forever. Runs once at start: the cost is a directory listing, and
 * doing it on a timer would be machinery for a problem that moves this slowly.
 */
function pruneCache() {
  const MAX_AGE_MS = 14 * 24 * 60 * 60 * 1000;
  try {
    if (!existsSync(CACHE_DIR)) return;
    const now = Date.now();
    let dropped = 0;
    for (const name of readdirSync(CACHE_DIR)) {
      const file = join(CACHE_DIR, name);
      try {
        if (now - statSync(file).mtimeMs > MAX_AGE_MS) {
          rmSync(file, { force: true });
          dropped++;
        }
      } catch {
        /* a file that vanished mid-sweep needs no handling */
      }
    }
    if (dropped) log(`cache: dropped ${dropped} stale file(s)`);
  } catch {
    /* pruning is housekeeping; never let it stop the bridge starting */
  }
}

function cacheKey(pathname, search) {
  return createHash("sha1").update(pathname + search).digest("hex");
}

function cachePaths(key) {
  return { body: join(CACHE_DIR, key + ".bin"), meta: join(CACHE_DIR, key + ".json") };
}

function cacheRead(key) {
  const { body, meta } = cachePaths(key);
  try {
    if (!existsSync(body) || !existsSync(meta)) return null;
    const head = JSON.parse(readFileSync(meta, "utf8"));
    return { head, body: readFileSync(body) };
  } catch {
    // A half-written or hand-edited entry is a miss, never a crash.
    return null;
  }
}

function cacheWrite(key, head, body) {
  if (body.length > CACHE_MAX_BYTES) return;
  try {
    if (!existsSync(CACHE_DIR)) mkdirSync(CACHE_DIR, { recursive: true });
    const paths = cachePaths(key);
    // Body first: a reader requires BOTH files, so writing the body before the
    // meta means an interrupted write reads as a miss rather than as a hit
    // with a truncated body.
    writeFileSync(paths.body, body);
    writeFileSync(paths.meta, JSON.stringify(head), "utf8");
  } catch {
    /* a cache that cannot write is just a slower bridge */
  }
}

/** Fetch from upstream and store. Returns {head, body} or null. */
async function fetchUpstream(pathname, search, etag) {
  const headers = {
    accept: "*/*",
    "accept-encoding": "identity",
    "user-agent": `promtly-bridge/${VERSION}`,
  };
  if (etag) headers["if-none-match"] = etag;
  const upstream = await fetch(`${UPSTREAM}${pathname}${search}`, {
    method: "GET",
    headers,
    redirect: "follow",
  });
  if (upstream.status === 304) return "unchanged";
  const body = Buffer.from(await upstream.arrayBuffer());
  const head = {
    status: upstream.status,
    type: upstream.headers.get("content-type") || "application/octet-stream",
    etag: upstream.headers.get("etag") || "",
    storedAt: Date.now(),
  };
  if (upstream.status === 200) cacheWrite(cacheKey(pathname, search), head, body);
  return { head, body };
}

function serveMirrored(res, head, body, isHead) {
  const isHtml = head.type.includes("text/html");
  const payload = isHtml ? Buffer.from(injectLocalLayer(body.toString("utf8"))) : body;
  const headers = {
    "content-type": head.type,
    // The BROWSER still must not cache: the bridge is the cache, and it is the
    // only layer that can tell a deploy from a stale page.
    "cache-control": "no-store",
    "content-length": String(payload.length),
  };
  res.writeHead(head.status, headers);
  res.end(isHead ? undefined : payload);
}

/**
 * Serve the board from this process, mirrored from promtly.dev.
 *
 * ⭐ Not a convenience. A page on https://promtly.dev asking
 * http://127.0.0.1 for something is a public-to-loopback request, and a
 * gated one hangs silently — measured 2026-09-17: the bridge answered curl
 * in 2 ms while the same request from the deployed board never completed.
 * Served from here the board is SAME-ORIGIN with the bridge, so there is
 * nothing to permit. It is still the deployed site; this only re-serves it
 * down loopback, through the cache above — so it opens instantly and works
 * offline, and a deploy lands on the revalidation behind the next open.
 */
async function proxyUpstream(req, res, url) {
  if (req.method !== "GET" && req.method !== "HEAD") {
    send(res, 405, { ok: false, error: "method not allowed" }, undefined);
    return;
  }

  const isHead = req.method === "HEAD";
  const key = cacheKey(url.pathname, url.search);
  const hit = cacheRead(key);

  if (hit) {
    serveMirrored(res, hit.head, hit.body, isHead);
    // Behind the response, never in front of it.
    if (Date.now() - (hit.head.storedAt || 0) > FRESH_MS && !revalidating.has(key)) {
      revalidating.add(key);
      fetchUpstream(url.pathname, url.search, hit.head.etag)
        .catch(() => null)
        .finally(() => revalidating.delete(key));
    }
    return;
  }

  try {
    const fresh = await fetchUpstream(url.pathname, url.search, "");
    if (fresh === "unchanged") {
      // Only reachable with an etag, which a miss never sends.
      res.writeHead(502, { "content-type": "text/plain" }).end("unexpected 304");
      return;
    }
    serveMirrored(res, fresh.head, fresh.body, isHead);
  } catch (err) {
    res.writeHead(502, { "Content-Type": "text/html; charset=utf-8" });
    res.end(
      `<!doctype html><meta charset="utf-8"><title>Promtly bridge</title>` +
        `<body style="background:#0B0F14;color:#F8FAFC;font:14px/1.6 system-ui;padding:48px;max-width:36rem">` +
        `<h1 style="font-weight:600">Cannot reach the board</h1>` +
        `<p style="color:#94A3B8">The bridge is running, but it could not fetch ` +
        `<code>${UPSTREAM}</code> and has nothing cached for this page yet: ` +
        `${String(err && err.message ? err.message : err)}</p>` +
        `<p style="color:#6F7E94">Open the launcher once with a connection and it will work ` +
        `offline after that. Pads still copy either way.</p></body>`,
    );
  }
}

const server = http.createServer(async (req, res) => {
  const origin = req.headers.origin;
  const allowed = typeof origin === "string" && ALLOWED_ORIGINS.has(origin);
  const url = new URL(req.url || "/", `http://127.0.0.1:${PORT}`);

  if (req.method === "OPTIONS") {
    if (!allowed) {
      res.writeHead(403).end();
      return;
    }
    res.writeHead(204, corsHeaders(origin)).end();
    return;
  }

  // Anything that is not this process's own API is the mirrored board.
  // Navigations carry no Origin header at all, so this has to come before
  // the origin check below or opening the local board 403s.
  if (!API_PATHS.has(url.pathname)) {
    await proxyUpstream(req, res, url);
    return;
  }

  // Endpoints that act on the machine require a browser that named itself.
  // A same-origin POST still sends Origin, so the mirrored board satisfies
  // this. Read-only endpoints also answer a same-origin GET (no Origin) and
  // plain curl.
  const readOnly =
    url.pathname === "/health" ||
    url.pathname === "/captures" ||
    // ⚠ GET only. /startup also WRITES on POST (it puts a script in the
    // Startup folder), and "read-only" here means "answers a request that
    // named no origin" - which a POST that changes the machine must not.
    (url.pathname === "/startup" && req.method === "GET") ||
    (url.pathname === "/update" && req.method === "GET") ||
    url.pathname === "/chairs" ||
    url.pathname.startsWith("/local/");
  if (!readOnly && !allowed) {
    send(res, 403, { ok: false, error: "origin not allowed" }, undefined);
    return;
  }
  if (readOnly && typeof origin === "string" && !allowed) {
    send(res, 403, { ok: false, error: "origin not allowed" }, undefined);
    return;
  }

  try {
    if (req.method === "GET" && url.pathname === "/health") {
      let target = "";
      let armed = false;
      if (driver) {
        try {
          const reply = await driver.target();
          target = reply.title;
          armed = reply.extra === "1";
        } catch {
          target = "";
        }
      }
      send(
        res,
        200,
        {
          ok: true,
          version: VERSION,
          platform: process.platform,
          supported,
          target,
          armed,
          captures: captures.length,
          hotkeys: hotkeys ? hotkeys.registered : null,
          latest: upstreamVersion,
          updateAvailable: updateAvailable(),
          // A checkout's bridge is updated with git; the UI hides the badge
          // rather than offering something that will refuse.
          updatable: !isDevelopmentCopy(),
        },
        origin,
      );
      return;
    }

    if (req.method === "GET" && url.pathname === "/local/version") {
      res.writeHead(200, { "Content-Type": "text/plain", "Cache-Control": "no-store" });
      res.end(localStamp());
      return;
    }

    if (
      req.method === "GET" &&
      (url.pathname === "/local/theme.css" || url.pathname === "/local/custom.js")
    ) {
      const isCss = url.pathname.endsWith(".css");
      res.writeHead(200, {
        "Content-Type": isCss ? "text/css; charset=utf-8" : "application/javascript; charset=utf-8",
        "Cache-Control": "no-store",
      });
      res.end(readLocal(isCss ? THEME_FILE : CUSTOM_JS));
      return;
    }

    if (req.method === "GET" && url.pathname === "/captures") {
      send(res, 200, { ok: true, captures }, origin);
      return;
    }

    if (req.method === "POST" && url.pathname === "/captures/clear") {
      const body = await readJson(req);
      const ids = Array.isArray(body.ids) ? new Set(body.ids) : null;
      const before = captures.length;
      for (let i = captures.length - 1; i >= 0; i -= 1) {
        if (!ids || ids.has(captures[i].id)) captures.splice(i, 1);
      }
      send(res, 200, { ok: true, cleared: before - captures.length }, origin);
      return;
    }

    // Wearing a pack's look. Writes exactly one file, always the same one.
    //
    // ⚠ There is deliberately NO write endpoint for custom.js. A stylesheet
    // cannot execute, so the worst a hostile theme can do is hide things;
    // script is a different category and stays something you place by hand.
    if (req.method === "POST" && url.pathname === "/local/theme") {
      const body = await readJson(req);
      const css = typeof body.css === "string" ? body.css : "";
      if (css.length > 400000) {
        send(res, 400, { ok: false, error: "theme too large" }, origin);
        return;
      }
      try {
        ensureLocalDir();
        writeFileSync(THEME_FILE, css, "utf8");
        log(`theme replaced (${css.length} chars) — the open window will follow`);
        send(res, 200, { ok: true, path: THEME_FILE }, origin);
      } catch (err) {
        send(res, 500, { ok: false, error: String(err && err.message ? err.message : err) }, origin);
      }
      return;
    }

    if (req.method === "GET" && url.pathname === "/chairs") {
      if (!driver) {
        send(res, 200, { ok: true, chairs: [] }, origin);
        return;
      }
      const reply = await driver.chairs();
      const chairs = reply.title
        .split("\n")
        .filter(Boolean)
        .map((line) => {
          const [name, title, alive] = line.split("\t");
          return { name, title: title || "", alive: alive === "1" };
        });
      send(res, 200, { ok: true, chairs }, origin);
      return;
    }

    if (req.method === "POST" && url.pathname === "/chairs/seat") {
      if (!driver) {
        send(res, 200, { ok: false, error: "unsupported platform" }, origin);
        return;
      }
      const body = await readJson(req);
      const name = typeof body.name === "string" ? body.name.trim().slice(0, 40) : "";
      if (!name) {
        send(res, 400, { ok: false, error: "name required" }, origin);
        return;
      }
      const reply = await driver.seat(name);
      log(`seated "${name}" = ${reply.title || "(untitled)"}`);
      send(res, 200, { ok: true, name, title: reply.title }, origin);
      return;
    }

    if (req.method === "POST" && url.pathname === "/chairs/unseat") {
      if (!driver) {
        send(res, 200, { ok: false, error: "unsupported platform" }, origin);
        return;
      }
      const body = await readJson(req);
      const name = typeof body.name === "string" ? body.name.trim() : "";
      await driver.unseat(name);
      send(res, 200, { ok: true }, origin);
      return;
    }

    /**
     * RELAY - one text, several chairs, in turn.
     *
     * This is the Promtly x Parley primitive. Seating two models at one table
     * means putting the same briefing in front of each of them, and doing it
     * by hand is the friction the whole idea dies on.
     *
     * Every chair is verified the way a single paste is: focus must actually
     * land, or that chair is reported refused and the loop moves on. A partial
     * relay is reported honestly rather than as success.
     */
    if (req.method === "POST" && url.pathname === "/relay") {
      if (!driver) {
        send(res, 200, { ok: false, error: "unsupported platform" }, origin);
        return;
      }
      const body = await readJson(req);
      const text = typeof body.text === "string" ? body.text : "";
      const wanted = Array.isArray(body.chairs)
        ? body.chairs.filter((c) => typeof c === "string")
        : [];
      const submit = body.submit === true;
      if (!text || wanted.length === 0) {
        send(res, 400, { ok: false, error: "text and chairs required" }, origin);
        return;
      }
      const results = [];
      for (const name of wanted) {
        const reply = await driver.paste(text, submit, name);
        results.push({ chair: name, status: reply.status, target: reply.title });
        log(`relay -> ${name}: ${reply.status}${reply.title ? ` (${reply.title})` : ""}`);
        // A breath between windows: a chat box just typed into is often still
        // settling, and the next focus change can be refused if it lands on
        // top of the last one.
        await new Promise((r) => setTimeout(r, 260));
      }
      send(res, 200, { ok: results.every((r) => r.status === "ok"), results }, origin);
      return;
    }

    // Get out of the way: put the window you summoned from back in front.
    if (req.method === "POST" && url.pathname === "/dismiss") {
      if (!driver) {
        send(res, 200, { ok: false, error: "unsupported platform" }, origin);
        return;
      }
      const reply = await driver.dismiss();
      send(res, 200, { ok: reply.status === "ok", target: reply.title }, origin);
      return;
    }

    if (req.method === "POST" && url.pathname === "/window") {
      if (!driver) {
        send(res, 200, { ok: false, error: "unsupported platform" }, origin);
        return;
      }
      const body = await readJson(req);
      const mode = body.mode === "peek" || body.mode === "hide" ? body.mode : "full";
      const reply = await driver.place(mode);
      send(res, 200, { ok: reply.status === "ok", status: reply.status, mode }, origin);
      return;
    }

    // Start-with-Windows as a TOGGLE rather than a flag you have to know.
    //
    // It was already there as --install-startup, which meant the one thing
    // that decides whether this is a tool or a demo - is it running when you
    // reach for it - needed a terminal and a remembered argument. On a second
    // machine that is the step you skip.
    if (url.pathname === "/startup") {
      if (process.platform !== "win32") {
        send(res, 200, { ok: false, installed: false, error: "windows only" }, origin);
        return;
      }
      if (req.method === "GET") {
        send(res, 200, { ok: true, installed: startupInstalled() }, origin);
        return;
      }
      if (req.method === "POST") {
        const body = await readJson(req);
        const code = manageStartup(body.install === false ? "uninstall" : "install");
        send(res, 200, { ok: code === 0, installed: startupInstalled() }, origin);
        return;
      }
    }

    if (url.pathname === "/update") {
      if (req.method === "GET") {
        await checkForUpdate(true);
        send(
          res,
          200,
          { ok: true, version: VERSION, latest: upstreamVersion, updateAvailable: updateAvailable() },
          origin,
        );
        return;
      }
      if (req.method === "POST") {
        const result = await installUpdate();
        send(res, 200, { ...result, from: VERSION }, origin);
        return;
      }
    }

    if (req.method === "POST" && (url.pathname === "/paste" || url.pathname === "/copy")) {
      if (!driver) {
        send(res, 200, { ok: false, error: `unsupported platform: ${process.platform}` }, origin);
        return;
      }
      const body = await readJson(req);
      const text = typeof body.text === "string" ? body.text : "";
      if (!text) {
        send(res, 400, { ok: false, error: "text required" }, origin);
        return;
      }
      const reply =
        url.pathname === "/paste"
          ? await driver.paste(
              text,
              body.submit === true,
              typeof body.chair === "string" ? body.chair : "",
            )
          : await driver.copy(text);
      // A status code is not an explanation. Every refusal here has a
      // different thing the person has to DO about it, so each one says what.
      const REASONS = {
        notarget: "No window to paste into — every candidate was minimised or ineligible.",
        nofocus:
          "Windows refused the switch, so the keystroke was not sent. Nothing was pasted anywhere.",
        clipfail: "Could not write to the clipboard; another app is holding it.",
      };
      send(
        res,
        200,
        {
          ok: reply.status === "ok",
          status: reply.status,
          target: reply.title,
          ...(reply.status !== "ok" && REASONS[reply.status] ? { error: REASONS[reply.status] } : {}),
        },
        origin,
      );
      log(
        reply.status === "ok"
          ? `pasted ${text.length} chars into "${reply.title}"${body.submit === true ? " and submitted" : ""}`
          : `paste ${reply.status}${reply.title ? ` (target "${reply.title}")` : ""}`,
      );
      return;
    }

    send(res, 404, { ok: false, error: "not found" }, origin);
  } catch (err) {
    send(res, 500, { ok: false, error: String(err && err.message ? err.message : err) }, origin);
  }
});

server.on("error", (err) => {
  if (err && err.code === "EADDRINUSE") {
    log(`port ${PORT} is already in use — a bridge is probably already running.`);
    process.exit(1);
  }
  throw err;
});

server.listen(PORT, "127.0.0.1", () => {
  pruneCache();
  // Behind the response, never blocking start: a bridge that will not come up
  // because promtly.dev is slow is worse than one that does not know it is old.
  setTimeout(() => void checkForUpdate(true), 2_000).unref?.();
  log(`Promtly bridge ${VERSION} listening on http://127.0.0.1:${PORT}`);
  if (!supported) {
    log(`platform ${process.platform} is not supported yet — clipboard, paste and`);
    log("hotkeys are Windows-only. The board is mirrored here but pads only copy.");
  } else {
    log("");
    log(`  the full board:  http://127.0.0.1:${PORT}/board`);
    log("");
    log("     Served from here on purpose: same-origin with this process, so");
    log("     there is no browser permission to negotiate. promtly.dev works");
    log("     too, but Chrome may gate its request and then pads only copy.");
  }
  if (ensureLocalDir()) {
    log("");
    log("  make it yours — these are on your machine and an assistant can edit them:");
    log(`     ${THEME_FILE}`);
    log(`     ${GUIDE_FILE}  (hand this to Claude or ChatGPT)`);
    log("     saved changes appear in the open window in about a second.");
  }

  log("");
  log("leave this window open. Ctrl+C to stop.");

  // Show, do not instruct. "Run it, then go and open a URL" is a step people
  // do not complete; opening the launcher once on start means the first thing
  // you see after double-clicking is the thing working. --no-open opts out.
  const suppressOpen = process.env.PROMTLY_NO_OPEN === "1" || argv.includes("--no-open");
  if (supported && !suppressOpen) {
    setTimeout(async () => {
      // !! Only if one is not already open.
      //
      // This opened unconditionally, so every restart of the bridge left
      // another launcher window behind - and they are Chrome --app windows,
      // which do not show up under Get-Process MainWindowTitle, so they pile
      // up invisibly. Restarting the bridge during a day's work is normal;
      // collecting a window each time is not.
      try {
        const state = await driver.launcherState();
        if (state.exists) {
          log("launcher already open — raising it instead of opening another");
          await driver.place("full");
          return;
        }
      } catch {
        // If the helper cannot answer, opening one is the better failure.
      }
      log("opening the launcher so you can see it working (--no-open to skip)");
      openLauncherWindow();
    }, 700);
  }
});

for (const signal of ["SIGINT", "SIGTERM"]) {
  process.on(signal, () => {
    if (driver && driver.proc) driver.proc.kill();
    if (hotkeys && hotkeys.proc) hotkeys.proc.kill();
    server.close(() => process.exit(0));
    setTimeout(() => process.exit(0), 500);
  });
}
