async function handleHotkey(id) {
  if (!driver) return;
  try {
    if (id === 1) {
      // Summon. Arm first — the launcher must not become its own target.
      // !! SUMMON ONLY - no hide-on-second-press, deliberately.
      //
      // A toggle was built here and taken out. It worked in isolation
      // (SHOWN/HIDDEN alternating on the chord) but its "is the launcher in
      // front?" test is only correct when the launcher is genuinely
      // foreground, and anything else holding focus - which is normal, since
      // you press this chord FROM another window - made it show when it should
      // hide and arm the wrong target on the way. A launcher that sometimes
      // vanishes when you summon it is worse than one that never hides.
      //
      // Escape in the launcher already dismisses it and hands focus back.
      const armed = await driver.arm();
      lastArmed = armed.title;
      log(`summon: target armed as "${armed.title || "(none)"}"`);
      const found = await driver.focusTitle(LAUNCHER_TITLE);
      if (found.status === "notfound") {
        openLauncherWindow();
        return;
      }
      // Now that FindByTitle exists, this actually raises the window it found
      // and parks it on the right edge.
      await driver.place("full");
      return;
    }
    if (id === 2) {
      const grabbed = await driver.grabSelection();
      const text = (grabbed.title || "").trim();
      if (!text) {
        log("capture: nothing was selected.");
        return;
      }
      captures.push({
        id: `cap_${Date.now().toString(36)}${Math.random().toString(36).slice(2, 6)}`,
        text,
        at: Date.now(),
      });
      log(`capture: ${text.length} chars held for the board (${captures.length} waiting)`);
    }
  } catch (err) {
    log(`hotkey ${id} failed: ${String(err && err.message ? err.message : err)}`);
  }
}

